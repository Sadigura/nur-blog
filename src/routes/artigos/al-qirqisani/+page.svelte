		<em>Kitab al-Anwar wal-Marakib</em>, foi traduzida ao hebraico como <em>Sefer Ha-Me'orot</em>,
		ou <em>Sefer ha-Ma'or</em>, e leva como subtítulo <em>Kitab al-Shara'i</em>
		(<em>Sefer Mitzvot Gadol</em>), por sua dedicação aos preceitos judaicos (mitzvot). Atribui-se a
		ele também um comentário intitulado <em>Al-Riyad wa-l-Hada'ik</em> (<em
			>Sefer ha-Gannim ve-Pardesim</em
		>, ou <em>Sefer ha-Nizzanim</em>), sobre as passagens do Pentateuco que não tratam diretamente
		das leis, o qual completaria o subtítulo acima mencionado. Alguns estudiosos, como Harkavy,
		acreditam, a partir de referências de outros autores medievais, que Qirqisani tenha traduzido a
		Bíblia ao árabe, além de ter escrito comentários também ao Livro de Jó e uma obra sobre a
		unidade de Deus, <em>Kitab al-Tawhid</em>.
	</p>
	<p>
		Composto em 13 tratados divididos em capítulos, o <em>Kitab al-Anwar</em> oferece muitas informações
