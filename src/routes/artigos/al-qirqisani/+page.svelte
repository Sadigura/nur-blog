		capítulos são uma introdução geral à obra e, em seu primeiro capítulo, dedica-se à explicação histórica
		do desenvolvimento das seitas judaicas, desde os Samaritanos até aquelas de seus dias. Afirma que o
		judaísmo rabanita é uma seita fundada por Jeroboam I, ainda que não apareça até o final do segundo
		templo.
