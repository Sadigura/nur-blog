	<p>
		Yehudah ben Samuel Há-Levi, ou Abû l Hasân ibn Al-Levi, hoje já é plenamente aceito que tenha
		nascido em Tudela, Espanha, entre 1070-75, seguindo o estabelecimento desta data por Schirmann,
		e não em Toledo, como vinham afirmando diversos estudiosos e ainda consignam alguns manuais de
		história literária. Mas, ainda a maior parte dos estudos antigos citam Toledo como sua cidade
		natal. O poeta medieval esteve em Zaragoza sob o governo dos Banu Hud, deslocando-se
		posteriormente para outras cidades de Al-Andalus, após breve parada em Toledo (que nesse
		momento já estava em mãos de Alfonso V), onde permaneceu por alguns anos. Retornou a Córdoba,
		onde se estabeleceu por algum tempo. Tendo frequentado os círculos intelectuais e literários da
		cidade, destacou-se por sua poesia. Conheceu Moshe Ibn Ezra, o qual, tornando-se seu amigo
		pessoal, convidou-o a ir a Granada. Lá permaneceu até 1090, quando, com a chegada dos
		Almorávidas, fugiu novamente para Toledo. Retornou a Al-Andalus, tendo residido em Córdoba,
		Granada e Sevilha. Exerceu a medicina em Castela e em algumas outras cidades de Al-Andalus.
		Sobre as datas de suas andanças não se tem notícia certa. Sabe-se ainda, por referências
		expressas em suas poesias, que se casou e teve uma filha e um neto.
	</p>
	<p>
		Com quase setenta anos, embarcou, em 1140, com destino a Alexandria; passou algum tempo no
		Egito, saindo alguns meses depois, novamente de navio, rumo à Palestina. A partir desse
		momento, seu rastro se perde. Sabe-se que morreu durante essa viagem, ainda que em
		circunstâncias misteriosas. De acordo com alguns autores, a data de sua morte é estipulada em
		1141, provavelmente ainda no Egito; de acordo com outros, Há-Levi morreu já em Jerusalém:
		"Jehuda Há-Levi parece ter conseguido a realização de seu desejo, e ter visitado Jerusalém,
		ainda que por um breve período" (Graetz, 1949, p. 342). Para outros estudiosos ainda, a data
		estimada é bem posterior, calculando-se que tenha ocorrido entre 1161 e 1170 (Orfali, 1997, p.
		61). A idéia de que teria sido assassinado em Jerusalém é, sem dúvida, uma bela estória, e
		bastante disseminada, embora não possa ser sustentada por evidências históricas. "A lenda de um
		Yehudá Há-Levi entrando em Jerusalém e ali sendo morto enquanto recitava uma poesia é uma bela
		lenda. Não é adequada à realidade histórica, mas será que ele próprio não teria gostado desse
		final?" (Doron, 1985, p. 13). Nesta época, as lendas acerca das circunstâncias de morte de
		personagens notáveis, especialmente figuras de expressão literária, eram extremamente comuns e
		ficavam praticamente incorporadas às suas biografias.
	</p>
	<p>
		Sendo médico de profissão, ficou mais conhecido por sua extensa obra poética de temática
		variada, bem como por sua obra fundamental, considerada, não sem reservas, no âmbito da
		filosofia. O "Livro da prova e fundamento da religião menosprezada" foi escrito originariamente
		em árabe, sob o título original de <em>Kitâb al-huyya wal-daIîl fî nusr-al-dîn al-dalil</em>,
		entre 1130 e 1140. Esta obra ficou conhecida pela tradução hebraica de Samuel Ibn Tibbon sob o
		nome de <em>Sefer Há-Kuzari</em>.
	</p>
	<p>
		Yehudá Há-Levi é considerado um dos maiores poetas religiosos do judaísmo medieval, tendo sido
		alguns de seus poemas incorporados à liturgia sefaradi do Yom Kippur. Em parte pelos elementos
		estruturais que toma de empréstimo a esta corrente filosófica, e que são expostos ao longo de
		sua obra célebre, o "Livro da prova e fundamento da religião menosprezada", do ponto de vista
		filosófico, é situado no âmbito do neoplatonismo — modelo afirmado por Isaac Israeli e Salomão
		Ibn Gabirol, que veio a se tornar dominante entre os séculos XI e XII, caindo em descrédito
		entre os pensadores judeus após o século treze. Guttmann assim justifica esta classificação
		controversa: "A singular figura de Yehudá Há-Levi não pertence a nenhuma escola filosófica.
		Apenas o fato de que alguns traços de seu pensamento o unem à tradição neoplatônica justifica
		discuti-lo nesse contexto" (Guttmann, Julius, 2003, p. 147). A nosso ver, esta caracterização de
		Yehudá Há-Levi enquanto neoplatônico parece bastante questionável, especialmente pelas críticas
		acirradas que dirige à filosofia e sua adesão ao criacionismo mais literal.
	</p>
	<p>
		Sua obra fundamental, texto escrito originariamente em árabe, segue um modelo dialógico,
		inspirada na história da conversão do rei Obadiah dos Khazares, ou Kuzari, um povo de origem
		turca estabelecido no baixo Volga que por volta de 680 ou 740 (de acordo com os diferentes
		autores) converte-se ao judaísmo. Este povo desapareceu em mãos dos bizantinos aliados de
		Vladimir da Rússia em 969, possivelmente tendo vindo seu rei, na época José, a se instalar em
		Córdoba depois da queda de seu reino. Há-Levi narra a história deste rei, que teria vivido uma
		experiência que se inicia com sonhos repetitivos, nos quais um anjo lhe aparecia e dizia: "tua
		intenção agrada ao Criador, mas as tuas obras não lhe são gratas" (Cuzary, p. 17). O rei então
		questiona as suas crenças religiosas e chama os diferentes "sábios" para que exponham as
		possíveis soluções para a sua inquietação. Interroga um filósofo, um teólogo cristão e um
		teólogo muçulmano. Não contente com as respostas que destes obtém, vê-se impelido a interrogar
		por último um doutor da minoria religiosa judaica, um rabino de nome Haver (termo hebraico que
		significa literalmente amigo, companheiro), o qual, por fim, convence o rei da veracidade e
		superioridade de suas crenças religiosas.
	</p>
	<p>
		Esta obra, longe de ser uma pura invenção, é uma ficção literária baseada no relato transmitido
		por Ma'sudí sobre a conversão de Bulan, rei dos Khazares, um grupo turco localizado nos Urais,
		que supostamente ocorrera no século VII. Este rei, ao adentrar as regiões que hoje constituem o
		Uzbequistão e o Turcomenistão, teria entrado em contato com o budismo, judaísmo, cristianismo e
		maniqueísmo, modificando seu xamanismo primitivo.
	</p>
