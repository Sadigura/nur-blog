	<p>
		Daud abu Sulaiman ibn Marwan Al-Muqammas, al Rakki, ou David Ha-Bavli, filósofo judeu morto
		cerca de 937. Tido por alguns como caraíta, é mencionado também como tendo se convertido ao
		Cristianismo. Nativo de Rakka, Mesopotâmia, viveu entre o nono e o décimo séculos. Contemporâneo
		mais velho de Saadia, é considerado o pai da Filosofia judaica medieval. Combina as concepções
		do Kalam com doutrinas filosóficas gregas que, neste autor, parecem ter mais influência do que
		em Saadia.
	</p>
	<p>
		Infelizmente, suas obras não estão disponíveis na íntegra. Entre suas obras figura
		<em>Ishrun maqalat</em>, ou os Vinte capítulos, dos quais quinze foram descobertos em 1898 na
		Biblioteca Imperial de S. Petersburgo. Versam sobre:
	</p>
	<ol class="works">
		<li>as categorias aristotélicas;</li>
		<li>a ciência e realidade de sua existência;</li>
		<li>a Criação do Mundo;</li>
		<li>a evidência de que ele é composto de substância e acidentes;</li>
		<li>as propriedades da substância e do acidente;</li>
		<li>crítica àqueles que sustentam a eternidade da matéria;</li>
		<li>argumentos a favor da existência de Deus e da Criação do Mundo;</li>
		<li>da unidade de Deus e a refutação das idéias dos sabeus, dualistas e cristãos;</li>
		<li>os atributos Divinos;</li>
		<li>refutação do antropomorfismo e das idéias cristãs;</li>
		<li>por que Deus se tornou Nosso Senhor;</li>
		<li>demonstração de que Deus criou o homem para o bem e não para o mal;</li>
		<li>a utilidade da profecia e dos Profetas;</li>
		<li>sinais da verdadeira profecia e dos verdadeiros profetas;</li>
		<li>mandamentos imperativos e proibitivos.</li>
	</ol>
	<p>
		No comentário ao <em>Sefer Yetsirah</em> de Judah Barzilai há uma tradução ao hebraico dos
		capítulos nove e dez. Al-Qirqisani menciona ainda duas outras obras de sua autoria, o
		<em>Kitab al-Khaliqah</em>, um comentário ao Gênesis extraído de fontes cristãs, e também um
		comentário ao Eclesiastes.
