	<p>
		Moshe ben Maimon, conhecido como Maimônides (1135-1204), foi médico, filósofo, e
		essencialmente um pensador judeu preocupado fundamentalmente com a compreensão de sua
		religião. Nascido na Espanha islâmica (Al-Andalus), durante sua adolescência, sua família é
		obrigada a migrar para Fez após a tomada do poder pelos Almôadas e, em 1168, segue para o
		Cairo. Estudou Medicina, vindo a se tornar médico do vizir Al-Fadil, homem de confiança de
		Saladino. Maimônides foi educado em ambiente marcado pelas discussões teológicas e sobre
		jurisprudência judaica — uma vez que consta que seu pai fora um dedicado estudioso do Talmud,
		tendo sido até mesmo juiz — e suas idéias seguem, em linhas gerais, a defesa das concepções
		majoritárias no judaísmo rabínico de sua época. Mas, ao contrário de um fideísta ou ingênuo
		defensor da literalidade das Escrituras, Maimônides lança mão, a fim de atingir seus
		objetivos, de sólida argumentação racional construída a partir dos grandes nomes da Filosofia,
		cujas obras conhecia profundamente, e dos filósofos islâmicos de seu tempo. Morreu em Fostat e
		foi enterrado em Tiberíades (Israel).
	</p>
	<p>
		Entre as obras voltadas à religião e a ética, tendo por base a produção talmúdica, como seus
		"Comentários à Mishná" e "Mishné Torah", surge sua obra principal, pela qual garante seu lugar
		na história da Filosofia: o "Guia para os Perplexos". Escrito originariamente em árabe, sob o
		título de <em>Dalalat al-'airin</em>, e traduzido ao hebraico como <em>Moreh Ha-Nevuchim</em>,
		o Guia compõe-se de três partes. A primeira consiste numa exposição dos "segredos" (sodot)
		contidos nos livros dos Profetas, a partir de uma exegese filológica de certos termos contidos
		na Bíblia, bem como uma profunda discussão sobre os atributos de Deus e uma crítica aos
		métodos do Kalam. A segunda parte do Guia dedica-se a estabelecer relações entre a Filosofia e
		os conteúdos das Escrituras, especialmente quanto à questão dos seres existentes e da criação
		do mundo, apontando suas proximidades e distâncias; desta parte consta também uma discussão
		sobre a questão da Profecia. A terceira parte do Guia discute questões sobre as disciplinas
		místicas judaicas (Maaseh Bereshit e Maaseh Merkabah), e trata de questões como a matéria, o
		mal, a Lei de Deus e a conduta do homem.
	</p>
	<p>
		O objetivo principal de Maimônides, conforme suas próprias palavras, era o de "esclarecer os
		pontos obscuros da Bíblia e expor explicitamente o verdadeiro sentido de seus fundamentos,
		encobertos à inteligência do povo" (Guia, II, 2). Conforme Maimônides, a verdade Revelada e a
		especulação filosófica só parecem diametralmente opostas a olhos despreparados e mentes
		ignorantes, posto que muitas das conclusões da filosofia somente vêm a reforçar a Verdade
		Revelada: "Assim, ao nos habituarmos com as opiniões dos ignorantes em Filosofia,
		inclinamo-nos a considerar estas opiniões filosóficas como estranhas à nossa religião (...) Mas,
		na verdade, não é assim" (Guia, II, 11).
	</p>
	<p>
		Muito embora acentue as semelhanças entre as concepções filosóficas, especialmente aquelas
		atribuídas a Aristóteles e aos peripatéticos islâmicos, e a revelação bíblica, estas
		semelhanças chegam a um limite na questão da Criação. Maimônides insiste em identificar pontos
		de concordância entre filosofia e revelação em questões como: a aceitação do modelo de
		esferas, o fato de que as esferas celestes sejam dotadas de alma e inteligência, o mundo
		governado por influências celestes, os corpos terrestres compostos de uma única e mesma
		matéria, sujeita à geração e à corrupção, o entendimento do processo de emanação ou processão
		como "influência" (equivalente do hebraico Shefa), e outras questões, tal como formuladas
		pelos filósofos, uma vez que possibilitariam o encontro de afirmações paralelas no texto
		bíblico, ainda que ali apareçam sob uma outra linguagem. Mas, no que se refere à origem
		primeira do Universo, estabelece a diferença fundamental e radical entre as duas posições.
	</p>
	<p>
		Destacam-se entre as obras de Maimônides, também as seguintes: sobre astronomia, o
		<em>Tratado sobre o calendário</em> (judaico) (1158) e <em>Carta aos Rabinos de Marselha sobre
			a astrologia</em
		> (1194). Entre suas cerca de dez obras de medicina, destacam-se
		<em>Aforismo médico de Moshé</em> (1187-1190), <em>Tratado sobre a asma</em> (1190),
		<em>Sobre o coito</em> (1191), <em>Sobre a higiene</em> (1198) e
		<em>Explicação das particularidades</em> (1200).
	</p>
