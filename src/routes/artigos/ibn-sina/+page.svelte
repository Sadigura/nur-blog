			que, quando suposto inexistente, decorre disto um absurdo. O ser possível é o que quando
			suposto inexistente ou existente, não decorre daí absurdo algum. O ser possível não é
			necessário, tanto no ser (no existir) como no não-ser (não existência).
		</p>
		<p>
			O ser necessário pode, ainda, sê-lo por si mesmo ou não por si mesmo. O ser necessário por
			si mesmo é o que é para si, não para outra coisa, seja o que for; torna-se absurdo não
			supô-lo desta forma.
		</p>
		<p>
			E o ser necessário não por si é aquilo que, quando se supõe alguma coisa que não seja ele,
