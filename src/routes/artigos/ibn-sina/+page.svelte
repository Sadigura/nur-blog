		<p>
			Ademais, a filosofia em terras do Islã surgiu impulsionada pela hermenêutica alcorânica. O
			desejo de conciliar razão e fé criou entre os muçulmanos um extraordinário movimento para
			explicação e interpretação do conteúdo do Livro Sagrado (o Alcorão).
		</p>
		<p>
			Se no Ocidente há separação entre ciência e religião, razão e fé, no Islã praticamente é
			inexistente este dualismo e, segundo Avicena, não há nada na filosofia que seja contrário à
			lei religiosa do Islã. Pode-se dizer que os filósofos muçulmanos do medievo procuraram
			estabelecer a harmonia entre filosofia e religião.
		</p>
		<p>
			Com menos de 18 anos de idade, Avicena, o Sumo Sheik ou o Grande Mestre (Al-Shaikh Al-Raís)
			como ficou conhecido no mundo árabe, já era médico e dominava conhecimentos amplos de
			filosofia, matemática, lógica, jurisprudência, teologia, entre outros. Produziu mais de
			duzentas obras. Merecem ênfase duas muito conhecidas: <em>O Cânon de Medicina</em> (<em
				>Kitáb Al-Qanún fi al-Tib</em
			>) e <em>Al-Shifá'</em> (a Cura). O Cânon foi traduzido para o latim por Gerardo de Cremona
			no final do século XII, tendo sido utilizado como base para os estudos de medicina nas
			universidades européias até o século XVII.
		</p>
		<p>
			Avicena foi um personagem louvável na união entre um conhecimento prático (a Medicina) e
			outro especulativo (a Filosofia), utilizando-se dos dois para ampliar os horizontes do
			conhecimento sobre o ser humano.
		</p>
		<p>
			<em>Al-Shifá'</em>, obra enciclopédica composta de 18 volumes que abrange metafísica,
			psicologia, física, matemática, astronomia e lógica, é dividida em quatro sumas da seguinte
			forma: metafísica, física, matemática e lógica. Cada suma é dividida em livros e cada livro
			é dividido em seções e as seções em capítulos. O próprio Avicena deixou claro o seu objetivo
			com esta obra. Ele afirmou:
		</p>
		<blockquote>
			Nossa intenção é pôr neste livro o fruto das ciências dos antigos que pudemos verificar;
			ciências baseadas numa dedução firme ou numa indução aceita pelos pensadores que buscam a
			verdade há muito tempo. Esforcei-me por incluir na obra a maior parte da filosofia... Não há
			nada de importante nos livros dos antigos que não figure nesta obra. Se algum elemento não
			for encontrado em seu contexto habitual, é porque o coloquei em outro lugar que considero
			mais conveniente<Sidenote n={3}
				>Ibrahim Bayumi Madkur, <em>O Correio da Unesco</em>, ano 8, nº 12, Rio de Janeiro, FGV,
				1980, p.15.</Sidenote
			>.
		</blockquote>
		<p>
			<em>Al-Shifá'</em> influenciou a elaboração do pensamento ocidental a partir do séc. XII,
			tendo em vista que algumas partes, como a metafísica e a psicologia, foram traduzidas para o
			latim.
		</p>
		<p>
			O pensamento filosófico de Avicena foi influenciado por filósofos da Grécia Antiga,
			particularmente pelas filosofias de Aristóteles, Platão (refuta, porém, a pré-existência das
			idéias ao modo platônico) e pelo neoplatonismo, mas não se pode dizer que ele foi fiel
			seguidor de alguma delas. Dos filósofos árabes foi influenciado, particularmente, por seu
			predecessor Al-Farabi, ao qual posteriormente ofuscou com a distinção que o conhecimento
			filosófico de Avicena recebeu.
		</p>
		<p>
			Por outro lado, influenciou de modo significativo o pensamento da Escolástica cristã na
			Idade Média em figuras como Tomás de Aquino, São Boa Ventura, Alexandre de Hales, João Duns
			Escoto, entre outros. Na sua monumental obra "Suma Teológica" (ou Suma de Teologia), Tomás
			de Aquino cita Avicena mais de 250 vezes, tanto para aceitar como para discordar do
			pensamento deste.
		</p>
		<p>
			Não há dúvida de que é o filósofo muçulmano dos conhecidos e o que mais projetou a filosofia
			escrita em árabe no Oriente e no Ocidente.
		</p>
		<p>
			A considerar suas atitudes, me atrevo a dizer que Avicena foi um homem religioso. Tudo
			indica que cultivava sua religião; o Islã, de modo sincero. Suas obras estão repletas de
			palavras de louvor a Deus e de exaltação do Profeta do Islã, Muhammad, e sua linhagem.
			Ninguém faz isto gratuitamente!
		</p>
		<p>
			Quando estava em dificuldade, procurava a mesquita como refúgio. Aí fazia suas preces e,
			muito provavelmente, sentia-se reconfortado espiritual e intelectualmente. Quem conhece o
			ambiente muçulmano sabe que esta prática é comum entre pessoas consideradas religiosas.
		</p>
		<p>
			Ibn Sina, ou Avicena, morreu no mês de Ramadã do ano de 428 da Hégira<Sidenote n={4}
				>Hégira: é o nome relativo ao calendário islâmico. A palavra Hégira (do árabe Hijra),
				designa a emigração de Muhammad (Profeta do Islã) de Meca para Medina. Isto ocorreu em 622
				da Era Cristã e corresponde ao ano 1 do calendário islâmico.</Sidenote
			>, correspondente ao mês de junho de 1037 d.C., próximo à cidade de Hamadan, na Pérsia.
			Nesta cidade, que conserva o mesmo nome, Avicena está sepultado num mausoléu e é motivo de
			orgulho para seus habitantes e para todos os iranianos<Sidenote n={5}
				>A antiga Pérsia hoje se chama República Islâmica do Irã.</Sidenote
			>. Junto ao mausoléu há várias dependências incluindo uma biblioteca. Hoje o local recebe
			muitas visitas de caráter turístico e acadêmico.
		</p>
		<p>
			Sua biografia nos foi passada por seu discípulo Abu 'Ubaid al-Juzjání, que o acompanhou por
			25 anos.
		</p>
		<p>
			Quanto à filosofia e sua divisão, o nosso filósofo divide a filosofia em especulativa e
			prática. Afirma, ainda, que "a filosofia é o aperfeiçoamento da alma humana". Isto se aplica
			tanto para o aperfeiçoamento relativo à razão, ao intelecto, pela apreensão de conceitos
			pertinentes às coisas e o assentimento das verdades relativas a estas, como para a filosofia
			prática, isto é, o agir humano. O poder de apreensão intelectual do ser humano é função
			exclusiva da alma humana. Esta alma é isenta de matéria e até mesmo de associação à matéria,
			afirma Ibn Sina. Para ele, a verdadeira noção de ser humano é aquela que inclui o que é
			essencial à essência deste ser humano e não apenas os elementos relativos às coisas
			percebidas pelos sentidos.
		</p>
		<p>
			A física aviceniana conserva os quatro elementos dos antigos (água, ar, terra e fogo) e
			divide os corpos em simples e compostos, sendo os primeiros indivisíveis em corpos de
			naturezas diferentes, porém, os corpos compostos podem dividir-se em corpos de formas
			diferentes.
		</p>
		<p>
			No âmbito da metafísica, ou filosofia primeira, Avicena sustenta que qualquer essência que
			não subsiste num sujeito é uma substância, e a essência que subsiste num sujeito é um
			acidente. Há que se destacar que nesta temática houve uma importante contribuição
			aviceniana para a época quando ele propôs a distinção real entre essência e existência,
			negando que a existência seja um simples acidente da essência. A existência é algo
			concreto, a essência é absolutamente abstrata.
		</p>
		<p>
			O elemento fundamental da metafísica aviceniana é a divisão do ser<Sidenote n={6}
