			>.
		</p>
		<p>
			Como se pode constatar, estes argumentos têm como base a lógica modal de Aristóteles<Sidenote
				n={8}>Pode-se conferir em <em>Peri Hermeneias</em>, cap. XII, 21ª ss.</Sidenote
			>. A exposição de Avicena sobre estas classes de ser tem como finalidade a prova da
			existência de apenas um ser necessário por si mesmo, por sua essência. Todos os demais
			seres dependem deste ser necessário.
		</p>
