		<p>
			Avicena é o nome latinizado de Abu Ali al-Hussein Ibn Abd Allah Ibn al-Hassan Ibn Ali Ibn
			Sina, ou simplesmente Ibn Sina, como é comumente chamado no mundo árabe. Ele nasceu no ano
			de 980 em Afshana, na antiga Pérsia, lugarejo hoje situado no Uzbequistão.
		</p>
		<p>
			Sem dúvida, este filósofo<Sidenote n={1}
				>Sobre a biografia de Avicena pode-se consultar o livro de GOHLMAN, William E. <em
					>The life of Ibn Sina</em
				>. New York: State University of New York Press, 1974. Esta biografia foi baseada no que o
				próprio Avicena ditou a Juzjání, seu discípulo por 25 anos, acrescida de informações do
				próprio Juzjání.</Sidenote
			> e médico pode ser considerado como um dos gênios da humanidade. Sua capacidade intelectual
			precoce foi evidenciada quando ele tinha apenas 10 anos de idade, pois nesta fase de sua vida
			já havia decorado todo o Alcorão, o Livro Sagrado dos muçulmanos. Há até um nome próprio em
			árabe – Háfiz – que designa de modo muito especial uma pessoa que tem o Alcorão memorizado<Sidenote
				n={2}
				>Algumas pessoas que sabiam o Alcorão de cor exerceram papel importante quando foi
				estabelecido o primeiro volume único e definitivo deste livro em 653.</Sidenote
			>. São aproximadamente 76.000 palavras, 114 capítulos (suwar) e cerca de 6.220 versículos
			(ayát). No contexto islâmico, esta atitude é uma proeza relevante porque é normal as pessoas
			se utilizarem de passagens do Alcorão tanto no âmbito da vida acadêmica como em questões
