	<p>
		Ibn 'Arabi, conhecido como al-Sheikh al-Akbar, o Mestre Maior, nasceu em Múrcia, Espanha
		andaluz, em 1165, numa família de nobres árabes, provavelmente de origem yemenita. Começou seus
		primeiros estudos ainda criança em Sevilha, sob orientação de seu pai, em língua e gramática
		árabe, direito islâmico, memorização e exegese do Alcorão e ditos do Profeta Muhammad. No
		início de sua adolescência surgiram suas primeiras experiências místicas, o que levou Ibn
		Rushd (Averróis), grande filósofo e jurista, a querer conhecê-lo. Neste encontro Ibn 'Arabi
		percebe a grande lacuna entre o pensamento racional e a via da revelação gnóstica, e inicia
		uma peregrinação tanto interior quanto exterior em busca de mestres, especialmente sufis, cujos
		nomes e ensinamentos deixou registrados em seu livro <em>Ruh al-Quds</em> (literalmente, o
		Espírito Santo), traduzido por R.J.W. Austin, como <em>Sufis of Andalusia</em>. Estas viagens
		tornaram-se o próprio ritmo de sua vida, seguindo de cidade em cidade por todo norte da África
		até Meca, Medina, Konya (Turquia) e Damasco, na Síria, onde falece em 1240 e onde seu túmulo é
		visitado até hoje.
	</p>
	<p>
		Frequentemente assinava suas obras como Abu Abdu Allah Muhammad ibn 'Arabi al-Ta'i al-Hatimi, e
		"Abdullah", o servo de Deus, é também uma das formas de entender sua extraordinária habilidade
		intelectual, visionária e mística: somente o <em>Futuhat al-Makiyya</em>, As Revelações de
		Meca, seu livro mais extenso, tem em torno de quinze mil páginas e 560 capítulos, tratando de
		cosmologia, metafísica, antropologia espiritual, psicologia, jurisprudência, estudos sobre
		profetas e sobre a língua árabe etc. É também uma fonte impressionante de relatos de
		experiências interiores e de vivências pessoais, pequenas crônicas de circunstâncias da vida de
		vários personagens, anedotas e poemas. A este seguem-se centenas de outras obras. Não se sabe
		ao certo, mas cento e dez manuscritos autênticos sobreviveram. Dentre os mais conhecidos, além
		do <em>Futuhat</em>, o <em>Fusus al-Hikam</em>, Gemas da Sabedoria, e o
		<em>Tarjuman al-Aswaq</em>, O intérprete dos desejos.
	</p>
	<p>
		Avesso aos teólogos, suas críticas e comentários lhe valeram a acusação de herege. Desconfiado
		da falsafa, a filosofia com base na tradição grega, tão pouco endossa completamente as
		tradições místicas, aproximando-se, em parte, aos malamatis, grupo cujo comportamento e
		atitudes opõem-se aos devotos e ascetas. Após sua morte, sua influência no mundo islâmico
		ampliou-se de modo ainda mais intenso e polêmico, tornando-se referência para filósofos do
		porte de Mulla Sadr, compêndio espiritual para diversos grupos sufis e inspiração para muitos
		movimentos sociais e culturais nos últimos oitocentos anos.
	</p>
	<p>
		É extremamente difícil articular seu pensamento de forma retilínea. Um conceito está
		intrinsecamente ligado a outro, sem início ou fim, numa complexitude simultaneamente
		multidimensional. A um nível esquemático básico podemos visualizar a correspondência entre três
		planos: o da vida manifesta no mundo, a vida interior do ser humano e o Alcorão. Esta
		inter-relação de dependência ficou conhecida como <em>wahdat al-wujud</em>, a unidade do ser.
		Ibn 'Arabi defendia a experiência de que só existe um único ser, que é o ser de Deus, cuja
		identidade, no sentido de experiência de si, permeia tudo o que existe. Para ele, o mundo e
		tudo o que vemos não existem em si, mas são manifestações dos diversos Nomes da identidade do
		Um, que chama de o Real, o Vivente. E este é o único modo de se conhecer tanto a si mesmo
		quanto ao mundo e a Deus. "Quem conhece (no sentido de "experiência") a si mesmo conhece
		(experiencia) seu Senhor", diz um hadith (dito profético) atribuído ao Profeta Muhammad. Ou
		seja, a identidade mais profunda de todos os seres é a forma pela qual estes seres reconhecem a
		Deus, a forma do Senhor pessoal, única e limitada a si mesmo. O divino em sua totalidade
		transcende a toda possibilidade de conhecimento, pois de forma alguma pode conter sua
		totalidade. Esta perspectiva é distinta do panteísmo, já que nem as criaturas são Deus, nem tão
		pouco a soma de tudo é Deus, como acontece na visão monista. A relação fica entre a forma e a
		identidade. A forma é a manifestação decorrente da identidade, não a identidade ela mesma: a
		forma é um "locus de manifestação" da expressão da identidade do Ser único. No entanto, a forma
		não está dissociada da identidade nem é externa a ela.
	</p>
	<p>
		Como a auto-exposição divina nunca se repete, cada indivíduo é existencializado de modo
		especifico e diferenciado, único, conforme o nome ou a combinação de nomes divinos atuantes em
		sua disposição, em seus múltiplos estados de ser, desde o corpo físico até sua entidade
		espiritual mais profunda. A atuação dos nomes se dá de modo luminoso e numinoso tendo o
		coração, núcleo essencial, como centro em torno do qual revolvem dando origem aos processos da
		vida tanto individual quanto coletiva.
	</p>
	<p>
		A existência de cada <em>wujud</em> está fundamentada na existência da realidade presente em
		seu coração, centro da própria identidade que em si é uma decorrência da existência divina.
		Deste modo, só o coração é capaz de conhecimento enquanto experiência, vivência direta de um
		"saborear" a presença da identidade, a presença do Real. A vida e a experiência de si mesmo
		enquanto ser humano dependem do acolhimento do influxo constante da presença divina em
		"desvelamento" continuamente renovado. O autoconhecimento seria então o reconhecimento da
		própria condição de "abdullah", de servo de Deus, aquele que, em si mesmo, é vazio de si.
	</p>
	<p>
		Por um outro lado, neste intrincado processo de metafísica do si mesmo, o universo e o Alcorão
		repetem o mesmo padrão aplicado ao ser humano: a cada plano ou nível de manifestação da
		identidade corresponde um plano da existência cósmica, num processo único de auto-exposição do
		sagrado. O Alcorão é visto como a revelação dos movimentos da existência, e sua interpretação é
		a interpretação simultânea do cosmos e do si mesmo. Para Ibn 'Arabi cada ser e cada momento
		está inscrito nestas três dimensões simultaneamente: no cosmos, no livro sagrado e na sua alma
		ou em si mesmo, e seus "sinais", ou "versos" (ayát) dão testemunho uns aos outros da presença
		que os permeia.
	</p>
	<p>
		Assim Ibn 'Arabi fundamenta seu pensamento numa hermenêutica do Alcorão que busca as raízes das
		palavras correspondentes a cada "respiração" do Todo Misericordioso. Este método origina uma
		abordagem das letras e da linguagem árabes sob múltiplos níveis de relação e constitui por si
		só um imenso estudo. O ponto em comum é a resposta das criaturas ao chamamento do ser (kún!
		Sê!) que deste modo as existencializa, donde a importância da palavra, tanto escrita quanto
		falada. Como palavra divina o Alcorão é um universo, do mesmo modo que a alma do ser humano
		também é um Alcorão, e estes valores se aplicam entre si em mútua assimilação.
	</p>
	<p>
		Como diz William Chittick, professor da Stony Brook University (Nova Iorque), "Ibn 'Arabi
		sempre foi considerado um autor dos mais difíceis. Isto devido a vários fatores, tanto pela
		extraordinária erudição quanto pelo discurso altamente consistente, contínua mudança de
		perspectivas e pela diversidade de estilos" (2005). E, apesar de partir fundamentalmente de uma
		perspectiva vivencial, fenomenológica, da hermenêutica mística e de ser considerado por muitos
		como um santo, a maior parte de seus escritos são argumentados com uma precisão racional tal
		que o coloca entre os principais intelectuais muçulmanos.
	</p>

