	<p>
		Schlomo ben Yehudá ben Gabirol, ou Abu Ayyub Sulayman b. Yahya Ibn Jabirwal (ou Ibn Yubayr,
		conforme Sa'id) foi poeta e filósofo. Nascido em Málaga por volta de 1021, no seio de uma
		família proveniente de Córdoba que emigrara, conforme nos relata Ibn Ezra, fugindo das revoltas
		que deram fim ao califado. Poucos anos depois, segue para a Taifa de Zaragoza, onde é educado
		nos melhores círculos literários e científicos. Ao que parece, fica órfão muito cedo.
	</p>
	<p>
		Muito importante em sua juventude é a amizade com Yequti'el Ibn Hasan (Al-Mutawakkil ibn
		Yishaq Abu Qapron). Em 1039 Yequti'el ibn Hassan é morto durante o golpe de Estado que afasta a
		dinastia governante, e Ibn Gabirol segue para Granada, em busca de um novo mecenas. Lá encontra
		Samuel Ibn Nagrella Há-Nagid, também poeta e político de prestígio, e se torna tutor de seu
		filho, Yosef; mas não consegue de Samuel o apoio que necessita para suas opiniões. Por
		conflitos políticos ou meramente literários, suas relações não foram muito estáveis, o que
		causou em pouco tempo seu retorno a Zaragoza, onde seus problemas políticos com seus
		correligionários poderosos se acirraram.
	</p>
	<p>
		Morto seu protetor e amigo Yequti'el e sem a proteção de Samuel Ibn Nagrella, teve de enfrentar
		a ira dos judeus de Zaragoza, que finalizou com a promulgação de um herem, sua expulsão da
		comunidade. Por volta do mesmo ano terminam as referências sobre Ibn Gabirol. Suas poesias
		sugerem que possivelmente em 1048 estivesse em Granada, mas sabe-se apenas que vagou pelo Sul
		da Espanha, sem que tenhamos condição de traçar com segurança o trajeto percorrido. Também não
		pode ser estabelecida com certeza a data da publicação de sua obra filosófica <em
			>A Fonte da Vida</em
		>, o que traz problemas para a identificação das fontes de seu pensamento.
	</p>
	<p>
		É corrente, embora pouco plausível, uma bela lenda difundida por Ibn Zacuto a respeito de Ibn
		Gabirol, que sustenta que o autor teria sido morto por um muçulmano, invejoso de seu grande
		talento. Este teria enterrado seu corpo sob uma figueira em seu jardim. A árvore passou a
		produzir frutos de doçura e tamanho extraordinários. Tendo ciência do fato, o rei mandou
		interrogar o dono do jardim, que foi obrigado a confessar o crime.
	</p>
	<p>
		A data de sua morte não é precisa. Sabe-se que não chegou a idade avançada. Al-Harizi aponta
		sua morte antes de 1050; Moshé ibn Ezra afirma ter sido em 1052; Al Mundir Ibn Sa'id
		al-Tulaituli, em 1058. Os autores posteriores, como Abraham Zacuto e Gediliah ibn Yahya, apontam
		sua morte em torno de 1070. A data considerada mais provável pelos estudiosos é entre 1050 e
		1059, mas é possível que tenha sido mais tardia, dado o volume, qualidade e maturidade dos
		escritos que nos legou. Há divergências também quanto ao local: Lucena ou Valencia.
	</p>
	<p>
		A obra filosófica fundamental de Ibn Gabirol foi escrita originariamente em árabe, sob o título
		<em>Yambu al-Hayyat</em> (A Fonte da Vida). Ibn Gabirol é considerado o primeiro autor
		metafísico espanhol, quando não, o primeiro filósofo espanhol propriamente dito. Sua obra
		filosófica foi utilizada por autores latinos, que desconheciam sua origem. Traduzido ao latim
		como <em>Fons Vitae</em>, por Juan Hispano e Domingo González, ainda no século seguinte (1150),
		passa ao patrimônio comum de textos estudados pela filosofia escolástica.
	</p>
	<p>
		Gabirol segue na mesma tendência de Filon de Alexandria e Ishaq Israeli, na tentativa de
		compatibilização do neoplatonismo com a religião bíblica. Mas, se podemos classificar o
		pensamento filosófico de Ibn Gabirol como neoplatônico — no sentido de apresentar um universo
		de emanações em que o que existe é em virtude da Forma que atualiza a Matéria — por outro lado,
		afasta-se da interpretação mais comum pela sua proposição original do hilemorfismo universal, e
		sua cosmologia torna-se profundamente hebraica no momento em que a estrutura de emanações é
		obra de um princípio supremo denominado Vontade. Para ele nada mais há que a realidade criada,
		composta por Matéria e Forma, a Essência Primeira e um intermediário entre os dois, que é a
		Vontade.
	</p>

	<h2>Obras</h2>
	<ul>
		<li>
			<em>Anaq</em> (1039) — originariamente em hebraico. Gramática hebraica em quatrocentos versos
			traduzida como "O Colar", da qual são conhecidos apenas noventa e oito, mais os dois da
			introdução, graças à sua inclusão em outra obra, o <em>Mahberet há-'aruk</em>, de Schlomo
			ibn Parhon;
		</li>
		<li>
			<em>Kitab islah al-ahlaq</em> (1045) — originariamente em árabe. Traduzido ao hebraico sob o
			nome <em>Tiqqun midot ha-nefesh</em> em 1167 por Ibn Tibbon, trata-se de um livro de ética
			psico-fisiológica;
		</li>
		<li>
			<em>Muhtar al yawahir</em> — originariamente em árabe. Trata-se de uma compilação de máximas,
			sentenças e historietas, conhecida por "Seleção de Pérolas". A tradução ao hebraico sob o
			nome <em>Mibhar ha-penînîm</em> adquiriu particular importância por ter sido o original
			perdido;
		</li>
		<li>
			<em>Yanbu' al-hayyat</em> — originariamente em árabe, a mais famosa e importante obra do
			autor; a única conhecida pelos cristãos; foi traduzida ao latim (<em>Fons Vitae</em>) pelos
			tradutores da Escola de Toledo (o converso Juan Hispano e Domingo Gundisalvo). Existe também
			a tradução hebraica resumida de Shem Tov Ibn Falaquera (séc. XIII) sob o título
			<em>Mekhor Hayyim</em>. O original árabe também foi perdido;
		</li>
		<li><em>Keter Malkut</em> — poema escrito em hebraico, formado por 40 cantos.</li>
	</ul>

	<p>
		O restante da produção poética de Ibn Gabirol — que passa de trezentas poesias — é por vários
		comentadores dividida entre secular e religiosa, ainda que certos estudiosos indiquem a imensa
		dificuldade desta separação. Pode-se concluir igualmente que nosso autor foi um excelso exegeta
		bíblico, pois é citado diversas vezes pelo grande comentarista Abraham Ibn Ezra, mas
		infelizmente nada nos chegou diretamente, portanto, não podemos, quanto a tal fato, utilizar
		nada além das próprias informações e indicações presentes neste e em outros autores. A obra de
		Ibn Gabirol era originariamente bem mais extensa, ele mesmo tendo feito referência a ter
		escrito umas vinte obras, mas apenas esta parte chegou até nossos dias. Temos referências
		(diretas e indiretas) a outros livros de sua autoria, mas, como ocorre em tantos outros
		autores, não podemos estabelecer se estes livros foram realmente escritos e perdidos, se foram
		atribuídos a outros autores, ou ainda, se não passaram de intenções do autor.
	</p>
