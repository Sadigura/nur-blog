	<h2>Apresentação</h2>
	<p>
		Esta proposta apresenta um minicurso introdutório dedicado à filosofia de Suhrawardi,
		proeminente filósofo persa do século XII, estruturado a partir de um problema filosófico
		central: a suficiência — ou insuficiência — da razão discursiva como fundamento do
		conhecimento.
	</p>
	<p>
		Sem perder seu caráter introdutório, o curso articula apresentação histórica e análise
		conceitual, abordando progressivamente a epistemologia, a ontologia da luz e a dimensão
		antropológica e simbólica do pensamento suhravardiano. Desse modo, oferece aos estudantes não
		apenas um primeiro contato com este autor, mas também uma via de acesso a questões filosóficas
		mais amplas sobre a natureza e os limites do conhecimento.
	</p>

	<h2>Justificativa e objetivos gerais</h2>
	<p>
		O minicurso proposto responde à necessidade de ampliar o repertório filosófico dos estudantes
		por meio do contato com tradições ainda pouco integradas ao currículo acadêmico, sem,
		contudo, restringir-se a uma abordagem meramente histórica ou descritiva. Ao tomar a filosofia
		de Suhrawardi como eixo, o curso introduz uma problemática central da filosofia: a relação
		entre razão, experiência e conhecimento.
	</p>
	<p>
		Nesse sentido, a proposta articula introdução histórica e análise conceitual, permitindo que
		os estudantes compreendam tanto o contexto de emergência do pensamento suhravardiano quanto a
		atualidade de suas questões.
	</p>
	<p>Os objetivos gerais do curso são:</p>
	<ol>
		<li>
			Apresentar a filosofia de Suhrawardi a partir de seu contexto histórico e intelectual,
			destacando suas relações com a tradição filosófica anterior, em especial com Avicena.
		</li>
		<li>
			Introduzir o problema dos limites da razão discursiva, explorando a distinção entre
			conhecimento representacional e conhecimento por presença.
		</li>
		<li>
			Desenvolver a capacidade dos estudantes de compreender e discutir conceitos filosóficos
			fundamentais em epistemologia e metafísica.
		</li>
		<li>
			Preparar os estudantes para estudos mais aprofundados, incluindo a leitura analítica das
			obras principais de Suhrawardi em módulos futuros.
		</li>
	</ol>

	<h2>Plano detalhado dos encontros</h2>

	<h3>Encontro 1 — Por que questionar a razão? Contexto, vida e projeto filosófico de Suhrawardi</h3>
	<p class="meta-line">26/08/2026, das 19:30 às 22:00</p>
	<p>
		<strong>Objetivo:</strong> introduzir o contexto histórico e intelectual de Suhrawardi a partir
		de um problema filosófico central: a suficiência — ou insuficiência — da razão discursiva como
		fundamento do conhecimento.
	</p>
	<ul>
		<li>
			Apresentação breve da vida de Suhrawardi (1154–1191) e das circunstâncias de sua morte,
			situando sua trajetória no interior de tensões intelectuais e institucionais de seu tempo.
		</li>
		<li>
			Panorama do século XII, com ênfase nas correntes filosóficas dominantes (especialmente a
			tradição peripatética) e na centralidade do modelo racional-discursivo de conhecimento.
		</li>
		<li>
			Formulação do problema: em que medida o conhecimento pode ser reduzido ao raciocínio e à
			argumentação? Introdução à hipótese de que nem todo conhecer se esgota em estruturas
			conceituais.
		</li>
		<li>
			Inserção de Suhrawardi nesse contexto como um filósofo que não rejeita a razão, mas
			questiona seus limites e propõe uma reconfiguração do saber.
		</li>
		<li>Relação com a tradição filosófica anterior, em especial Avicena, destacando continuidade e ruptura.</li>
		<li>
			Apresentação geral de suas obras principais (<em>Hikmat al-Ishrâq</em>, <em>Talwihât</em>,
			<em>Muqawamât</em>, <em>al-Mashâri' wa al-Mutarahât</em> e tratados simbólicos), situando-as
			no interior de seu projeto filosófico.
		</li>
	</ul>
	<p>
		<strong>Resultado esperado:</strong> ao final do encontro, os estudantes deverão reconhecer que
		a filosofia de Suhrawardi emerge de um problema epistemológico preciso — os limites da razão
		discursiva — e compreender sua posição no contexto da história da filosofia como uma resposta
		original a esse problema.
	</p>

	<h3>Encontro 2 — O que é conhecer? Razão, presença e os limites do conhecimento discursivo</h3>
	<p class="meta-line">02/09/2026, das 19:30 às 22:00</p>
	<p>
		<strong>Objetivo:</strong> examinar a concepção de conhecimento em Suhrawardi a partir da
		distinção entre conhecimento discursivo e conhecimento por presença, aprofundando o problema
		dos limites da razão apresentado no encontro anterior.
	</p>
	<ul>
		<li>Retomada do problema central: o conhecimento pode ser reduzido à argumentação e à representação conceitual?</li>
		<li>
			Distinção entre sabedoria discursiva (baseada em conceitos e inferências) e sabedoria
			iluminativa, introduzida como uma forma de acesso não mediado ao real.
		</li>
		<li>Crítica às limitações do raciocínio puramente silogístico, não como rejeição da razão, mas como delimitação de seu alcance.</li>
		<li>
			Introdução à noção de ciência por presença (<em>ʿilm al-ḥuḍūrī</em>) em contraste com a
			ciência por representação, com exemplos simples (como a autoconsciência e a experiência
			imediata) para tornar a distinção inteligível.
		</li>
		<li>O papel da intuição, da experiência direta e da interioridade na constituição do conhecimento, evitando leituras meramente místicas ou irracionalistas.</li>
		<li>Reconfiguração da relação entre razão, iluminação e verdade: a razão como condição necessária, mas não suficiente, do conhecimento.</li>
	</ul>
	<p>
		<strong>Resultado esperado:</strong> ao final do encontro, os estudantes deverão compreender
		que, em Suhrawardi, nem todo conhecimento é de natureza representacional ou discursiva, e que
		a noção de conhecimento por presença introduz um modelo epistemológico que amplia — sem
		abandonar — o papel da razão filosófica.
	</p>

	<h3>Encontro 3 — Se o conhecimento é presença, o que é o ser? A ontologia da luz em Suhrawardi</h3>
	<p class="meta-line">09/09/2026, das 19:30 às 22:00</p>
	<p>
		<strong>Objetivo:</strong> introduzir a estrutura ontológica da filosofia de Suhrawardi como
		desdobramento direto de sua concepção de conhecimento, mostrando por que uma epistemologia da
		presença exige uma metafísica da luz.
	</p>
	<ul>
		<li>Retomada do problema: se o conhecimento não é apenas representação, mas presença, então o que deve ser a realidade para que tal conhecimento seja possível?</li>
		<li>Apresentação do princípio ontológico fundamental: a luz como realidade primeira, aquilo que se manifesta por si e torna outras coisas manifestas.</li>
		<li>Estrutura hierárquica do ser: Luz das Luzes, luzes dominantes e luzes administradoras, compreendidas como graus de intensidade e manifestação.</li>
		<li>A escuridão e a sombra não como realidades autônomas, mas como níveis de privação ou enfraquecimento da luz.</li>
		<li>Introdução aos principais conceitos do sistema: luz pura, luzes suspensas, substâncias escuras e corpos materiais, apresentados de modo gradual e acessível.</li>
		<li>O papel do domínio imaginal (<em>ʿālam al-mithāl</em>) como nível intermediário de realidade, articulando o sensível e o inteligível.</li>
		<li>Aproximações e diferenças em relação a tradições neoplatônicas, enfatizando a originalidade da proposta suhravardiana.</li>
	</ul>
	<p>
		<strong>Resultado esperado:</strong> ao final do encontro, os estudantes deverão compreender
		que a ontologia da luz não constitui um elemento simbólico isolado, mas uma estrutura
		metafísica coerente que responde à exigência de um conhecimento por presença, redefinindo a
		relação entre ser e conhecer.
	</p>

	<h3>Encontro 4 — Quem conhece? Alma, experiência e a realização do conhecimento em Suhrawardi</h3>
	<p class="meta-line">16/09/2026, das 19:30 às 22:00</p>
	<p>
		<strong>Objetivo:</strong> examinar como a concepção suhravardiana do ser humano decorre de sua
		ontologia da luz, mostrando que o conhecimento por presença implica uma transformação na
		compreensão da alma, da experiência e da relação com o mundo.
	</p>
	<ul>
		<li>Retomada da questão central: se conhecer é estar em presença, quem — ou o que — é o sujeito do conhecimento?</li>
		<li>A alma como uma luz administradora, situada na hierarquia do ser e capaz de graus de intensidade cognitiva.</li>
		<li>O conhecimento como forma de união ou presença direta do objeto conhecido, para além da mediação puramente conceitual.</li>
		<li>Relação entre corpo e alma: níveis de consciência, limitações da percepção sensível e o papel da imaginação ativa como mediação entre diferentes planos da realidade.</li>
		<li>Dimensão existencial do conhecimento: implicações éticas e formativas, incluindo a ideia de distanciamento das "trevas" associadas à fixação no nível material.</li>
		<li>Articulação com questões contemporâneas em filosofia da mente e epistemologia (como consciência, experiência subjetiva e formas não-representacionais de conhecimento), indicando a atualidade do problema.</li>
	</ul>
	<p>
		<strong>Resultado esperado:</strong> ao final do encontro, os estudantes deverão compreender
		que, em Suhrawardi, o conhecimento não é apenas uma operação intelectual, mas envolve a
		própria estrutura e condição do sujeito, integrando ontologia, epistemologia e experiência em
		um único quadro filosófico.
	</p>

	<h3>Encontro 5 — Se o conhecimento excede o conceito: linguagem, símbolo e expressão filosófica em Suhrawardi</h3>
	<p class="meta-line">23/09/2026, das 19:30 às 22:30</p>
	<p>
		<strong>Objetivo:</strong> examinar a função filosófica da linguagem simbólica e das
		narrativas visionárias em Suhrawardi como resposta aos limites da expressão conceitual,
		articulando-as com sua teoria do conhecimento por presença.
	</p>
	<ul>
		<li>Retomada do problema final do curso: se nem todo conhecimento é discursivo, a linguagem conceitual é suficiente para expressá-lo?</li>
		<li>A linguagem simbólica como forma de expressão filosófica, não como recurso literário secundário, mas como meio adequado a conteúdos que excedem a representação conceitual.</li>
		<li>
			Análise da função das narrativas visionárias (como <em>O Arcanjo Rubro</em>,
			<em>A Lenda do Ocidente</em> e <em>O Canto da Asa de Gabriel</em>) enquanto dispositivos de
			acesso e transmissão do conhecimento.
		</li>
		<li>A jornada ascendente da alma no imaginário luminífero, compreendida como estrutura cognitiva e não apenas alegoria espiritual.</li>
		<li>Relação entre símbolo, imaginação e conhecimento, retomando o papel do domínio imaginal na mediação entre níveis de realidade.</li>
		<li>Impacto histórico da obra de Suhrawardi na filosofia iraniana posterior e sua recepção moderna no Ocidente, com destaque para as leituras de Henry Corbin e debates contemporâneos sobre hermenêutica e linguagem.</li>
	</ul>
	<p>
		<strong>Resultado esperado:</strong> ao final do encontro, os estudantes deverão compreender
		que, em Suhrawardi, o recurso ao símbolo e à narrativa não indica um afastamento da filosofia,
		mas uma ampliação de seus meios de expressão, coerente com uma concepção de conhecimento que
		ultrapassa os limites do discurso conceitual. O curso se encerra com os alunos aptos a
		prosseguir, em módulos futuros, para uma leitura analítica da <em>Hikmat al-Ishrâq</em> e dos
		tratados visionários.
	</p>

