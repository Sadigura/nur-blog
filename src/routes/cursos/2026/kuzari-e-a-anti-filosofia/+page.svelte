	<h2>Justificativa</h2>
	<p>
		Considerado um autor neoplatônico, Yehuda HaLevi (1075-1141) é essencialmente um defensor do
		judaísmo. Assim como seu antecessor muçulmano Abu Hamid Al-Ghazzali, HaLevi utiliza seu amplo
		conhecimento da filosofia anterior e contemporânea não para apresentar uma teoria filosófica,
		mas para criticar os filósofos. Sua obra "O Kuzari" é apresentada não como um tratado, mas
		como uma história que está sendo contada. Foi inspirada na história, por muitos considerada
		real, da conversão ao judaísmo do rei dos Khazares, povo seminômade de origem turcomana que
		manteve um poderoso canato localizado entre o norte do Cáucaso, o sul da Rússia, a Ucrânia e o
		oeste do Cazaquistão. Começando a narrativa por um sonho do rei no qual um anjo fala com ele,
		este convoca vários sábios a fim de buscar respostas. A obra prossegue então na forma de
		diálogo, na sua maior parte com o sábio judeu, que consegue a atenção do rei e passa a
		demonstrar os erros das demais religiões monoteístas e do pensamento dos filósofos. A obra é
		importante, sobretudo para demonstrar o conhecimento da filosofia por parte dos pensadores
		religiosos, ainda que discordassem de seus métodos.
	</p>

