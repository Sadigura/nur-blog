	<h2>Objetivo</h2>
	<p>
		Introduzir a tradição chassídica do Baal Shem Tov por meio de suas histórias e textos
		fundamentais, como o <em>Keter Shem Tov</em> e o <em>Shivhei HaBesht</em>, e explorar as
		escolas chassídicas que herdaram seus ensinamentos, apresentando suas narrativas e obras
		essenciais, incluindo o <em>Tanya</em> (Rabino Shneur Zalman de Liadi), <em>Mei HaShiloach</em>
		(Rabino Mordechai Leiner de Izhbitz-Radzin) e <em>Likkutei Moharan</em> (Rabino Nachman de
		Breslov), entre outras.
	</p>

	<h2>Justificativa</h2>
	<p>
		O curso "Filosofia Chassídica: Cinco Horizontes do Baal Shem Tov" é parte integrante de um
		ciclo de cursos de curta duração oferecidos dentro do projeto de extensão "Histórias de
		Sabedoria e Ensinamento". Como projeto organizado pelos integrantes do NUR – Núcleo de
		Pesquisas em Filosofia Islâmica, Judaica e Oriental da Unifesp, os cursos abordam as
		tradições do Judaísmo, Islamismo, China e Japão.
	</p>
	<p>
		Este curso propõe uma análise das narrativas tradicionais em hebraico relacionadas ao Baal
		Shem Tov, fundador do chassidismo, e às suas escolas herdeiras, por meio da leitura de
		histórias e textos chassídicos fundamentais, como o <em>Shivhei HaBesht</em>, o
		<em>Keter Shem Tov</em> e obras posteriores, incluindo o <em>Tanya</em> e o
		<em>Likkutei Moharan</em>. O objetivo é investigar, a partir de uma perspectiva filosófica, as
		implicações éticas, ontológicas e epistemológicas presentes nessas narrativas, oferecendo uma
		compreensão rigorosa e contextualizada das ideias chassídicas enquanto expressão de uma
		tradição filosófica e espiritual judaica.
	</p>

	<h2>Metodologia</h2>
