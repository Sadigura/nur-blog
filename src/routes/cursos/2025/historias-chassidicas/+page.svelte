	<h2>Conteúdo programático</h2>
	<p>
		Na primeira aula, serão apresentados os conceitos fundamentais do Chassidismo, incluindo o
		que é um Rebbe e qual é sua função espiritual dentro da comunidade chassídica. Serão
		abordadas as bases históricas e filosóficas que sustentam a transformação promovida pelo
		movimento chassídico no Judaísmo tradicional, com destaque para a revolução espiritual
		iniciada pelo Baal Shem Tov. Além disso, exploraremos a vida e o legado do Baal Shem Tov,
		analisando histórias populares atribuídas a ele presentes em textos como o
		<em>Keter Shem Tov</em> e o <em>Shivhei HaBesht</em>.
	</p>
	<p>
		Nas aulas seguintes, o curso abordará, de maneira resumida, a história de diversas dinastias
		chassídicas que herdaram os ensinamentos do Baal Shem Tov, como Chabad-Lubavitch, Breslov,
		Zidichov-Komarno e Izhbitz-Radzin. Na segunda aula, será dada especial atenção ao movimento
		Chabad-Lubavitch, começando pela apresentação de histórias atribuídas a seus primeiros
		líderes, incluindo o Alter Rebbe (Shneur Zalman de Liadi), o Mitteler Rebbe, o Tzemach Tzedek
		e o Rebbe Rayatz. A partir dessas narrativas, serão introduzidos conceitos fundamentais da
		filosofia chassídica Chabad, que enfatiza a intelectualização da espiritualidade por meio do
		entendimento das dimensões de Chochmah (sabedoria), Binah (compreensão) e Da'at
		(conhecimento). Como contraponto, apresentaremos a dinastia Zidichov-Komarno, uma corrente
		menos conhecida do Chassidismo, mas que oferece perspectivas significativamente diferentes
		das ideias chabadianas.
	</p>
	<p>
		Na quarta aula, o foco será o movimento Izhbitz-Radzin, uma importante ramificação da
		Chassidut polonesa. Este movimento é conhecido por suas contribuições originais à filosofia
		chassídica, particularmente em relação às ideias de agência e livre-arbítrio. A aula abordará
		as reflexões inovadoras de figuras centrais como Mordechai Yosef Leiner (autor do
		<em>Mei HaShiloach</em>), Menachem Mendel de Kotzk e R' Tzadok HaCohen. Serão exploradas as
		implicações filosóficas de suas ideias, especialmente no que tange à tensão entre a liberdade
		humana e a providência divina.
	</p>
	<p>
		Por fim, na última aula, o curso se concentrará no movimento Breslov, fundado pelo Rabino
		Nachman de Breslov, e em sua abordagem única das narrativas chassídicas. Será analisado como
		as histórias servem como um veículo central para a transmissão de ensinamentos espirituais e
		éticos no pensamento Breslov, com base em textos como o <em>Likkutei Moharan</em>. Além disso,
		será discutido o papel das narrativas na criação de novas formas de reflexão espiritual,
		destacando a ideia do Rabino Nachman de utilizar as histórias como uma ferramenta para
		conectar o indivíduo com sua própria jornada espiritual.
	</p>

