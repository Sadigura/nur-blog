	<h2>Objetivo</h2>
	<p>
		Oferecer uma apresentação dos termos-chave que compõem a linguística antropológica da
		<em>tanak</em> (Bíblia Hebraica).
	</p>

	<h2>Justificativa</h2>
	<p>
		Ao longo dos seus nove séculos de composição, a literatura hebraica bíblica registra o
		desenvolvimento de uma linguística antropológica peculiar. Seus termos-chave apresentam um
		caráter polissêmico e polivalente. Os termos <em>ruaḥ</em>, <em>nefeš</em> e <em>leb</em>,
		comumente traduzidos como espírito, alma e coração, respectivamente, apresentam uma gama de
		significados. O exame minucioso e contextual desses termos apresenta ao leitor moderno uma
		leitura sofisticada da condição humana, propondo questões filosóficas que atravessam os
		séculos.
	</p>

	<h2>Metodologia</h2>
	<p>Aulas expositivas e interativas online por videoconferência através do Google Meet.</p>

	<h2>Conteúdo programático</h2>
	<p>
		Na primeira aula será realizado uma apresentação das características gerais da linguagem da
		Bíblia Hebraica, destacando a expressão conceitual por meio do pensamento sintético e
		figurativo (a citação de órgãos característicos aludindo à sua função). Discutiremos essa
		conceitualidade singular (<em>Eigenbegrifflichkeit</em>) da antropologia hebraica em
		contraste com os traços da antropologia helênica. Na segunda e terceira aula, discutiremos a
		riqueza de significação das palavras que descrevem a condição humana. O modo como o texto
		bíblico delineia a composição orquestral da tríade desejos (<em>nefeš</em>), carisma
		(<em>ruaḥ</em>) e consciência (<em>leb</em>), a partir de uma noção peculiar de tempo, serão
		objeto de análise.
	</p>

